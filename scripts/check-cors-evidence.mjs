#!/usr/bin/env node
/* check-cors-evidence.mjs — keep the published CORS claim tied to the measured evidence.
 *
 * WHY THIS EXISTS
 * ---------------
 * F-01 ("browser access to the demo API could not be tested") sat open for a day. It was closed on
 * 2026-11-21 by measurement (tools/cors_probe.mjs → data/cors-probe.json, two runner runs), and that
 * measurement also produced a NEW limitation (F-66): the preflight does not allow the
 * KALSHI-ACCESS-* headers, so a static page cannot sign requests at all.
 *
 * A measured claim decays in two ways, and both are silent:
 *   1. the evidence file is edited (or regenerated by a different API behaviour) while the published
 *      page keeps asserting the old conclusion;
 *   2. the corrected copy regresses — someone re-adds "signs requests in your browser from a key you
 *      paste", which is now known to be impossible.
 *
 * This checker recomputes every verdict from the recorded headers alone (it never trusts the stored
 * `readable_from_browser` field), then asserts the page matches the evidence in both directions.
 * It is offline and dependency-free: no network, no jsdom.
 *
 * NOT A SUBSTITUTE FOR THE PROBE: it cannot discover the current CORS policy; it only refuses to let
 * the repository claim something its own recorded evidence contradicts. Re-run the `cors-probe`
 * workflow to refresh data/cors-probe.json.
 *
 * Sources for the rules enforced here:
 *   CORS protocol / preflight: https://fetch.spec.whatwg.org/#http-cors-protocol
 *   Required auth headers:     https://docs.kalshi.com/getting_started/quick_start_authenticated_requests.md
 */
import { readFileSync, existsSync } from 'node:fs';

const EVIDENCE = 'data/cors-probe.json';
const SITE_ORIGIN = 'https://kanlerxz87-cyber.github.io';
const AUTH_HEADERS = ['kalshi-access-key', 'kalshi-access-signature', 'kalshi-access-timestamp'];

let failures = 0;
let checks = 0;

function ok(msg) {
  checks++;
  console.log(`ok   ${msg}`);
}
function bad(msg) {
  checks++;
  failures++;
  console.error(`FAIL ${msg}`);
}

/* --- 1. evidence file exists and is a real measurement --------------------- */
if (!existsSync(EVIDENCE)) {
  console.error(`FAIL ${EVIDENCE} is missing. The published CORS claim has no evidence; re-run the cors-probe workflow.`);
  process.exit(1);
}
const report = JSON.parse(readFileSync(EVIDENCE, 'utf8'));

if (report.probe_origin !== SITE_ORIGIN) {
  bad(`probe_origin is "${report.probe_origin}", expected the published site origin ${SITE_ORIGIN}`);
} else {
  ok(`probe used the published site origin (${SITE_ORIGIN})`);
}

if (!Array.isArray(report.results) || report.results.length === 0) {
  bad('no results recorded in the evidence file');
  console.log(`\n${failures} failure(s).`);
  process.exit(1);
}
ok(`evidence file carries ${report.results.length} recorded requests`);

/* --- 2. every stored verdict must follow from that record's own headers ---- */
function derive(headers) {
  const acao = headers && headers['access-control-allow-origin'];
  if (!acao) return false;
  if (acao.trim() === '*') return true;
  return acao.trim() === SITE_ORIGIN;
}

let measurable = 0;
for (const r of report.results) {
  if (r.error) {
    if (r.readable_from_browser && r.readable_from_browser.allowed !== null) {
      bad(`${r.name}: a failed request recorded a readable=${r.readable_from_browser.allowed} verdict`);
    } else {
      ok(`${r.name}: failed request recorded as unknown (no verdict invented)`);
    }
    continue;
  }
  measurable++;
  const expected = derive(r.headers);
  const stored = r.readable_from_browser && r.readable_from_browser.allowed;
  if (stored === expected) {
    ok(`${r.name}: stored verdict matches its own headers (readable=${expected})`);
  } else {
    bad(`${r.name}: stored verdict ${stored} contradicts its recorded headers (headers imply ${expected})`);
  }
}
if (measurable < 6) {
  bad(`only ${measurable} completed public request(s) recorded; the summary needs at least 6 to be meaningful`);
} else {
  ok(`${measurable} completed requests recorded`);
}

/* --- 3. the summary must not claim more than the requests show ------------- */
const publicRows = report.results.filter((r) => r.name !== 'portfolio_balance_no_key' && !r.error);
const allReadable = publicRows.length >= 5 && publicRows.every((r) => derive(r.headers));
const sum = report.summary || {};
if (sum.browser_can_read_public_endpoints === allReadable) {
  ok(`summary.browser_can_read_public_endpoints matches the recorded headers (${allReadable})`);
} else {
  bad(`summary claims browser_can_read_public_endpoints=${sum.browser_can_read_public_endpoints} but the headers imply ${allReadable}`);
}

/* --- 4. F-66's premise must still be in the evidence ---------------------- */
const preflights = Array.isArray(report.preflights) ? report.preflights : [];
if (preflights.length === 0) {
  bad('no preflight recorded — the F-66 claim needs one');
}
for (const p of preflights) {
  const allowed = String((p.headers && p.headers['access-control-allow-headers']) || '').toLowerCase();
  const missing = AUTH_HEADERS.filter((h) => !allowed.includes(h));
  if (missing.length === AUTH_HEADERS.length && p.allows_requested_headers === false) {
    ok(`${p.name}: preflight still lacks every KALSHI-ACCESS-* header (F-66 holds)`);
  } else {
    bad(`${p.name}: preflight now allows ${missing.length === 0 ? 'all' : 'some'} KALSHI-ACCESS-* headers — F-66's published text is out of date`);
  }
}

/* --- 5. the published page must match the evidence, both directions ------- */
const flagged = existsSync('flagged.html') ? readFileSync('flagged.html', 'utf8') : '';
const rowFor = (id) => {
  const start = flagged.indexOf(`id="${id}"`);
  if (start === -1) return '';
  const end = flagged.indexOf('</tr>', start);
  return end === -1 ? '' : flagged.slice(start, end);
};

for (const id of ['F-01', 'F-51']) {
  const row = rowFor(id);
  if (!row) {
    bad(`${id} is missing from flagged.html`);
  } else if (!/Resolved/i.test(row)) {
    bad(`${id} exists but is not marked Resolved, while the evidence records readable public endpoints`);
  } else if (!row.includes('cors-probe.json')) {
    bad(`${id} is marked Resolved but does not link the evidence file`);
  } else {
    ok(`${id} marked Resolved and links the measured evidence`);
  }
}

const f66 = rowFor('F-66');
if (!f66) {
  bad('F-66 is missing from flagged.html, but the preflight evidence still shows the auth headers are refused');
} else if (!/KALSHI-ACCESS-KEY/.test(f66)) {
  bad('F-66 exists but does not name KALSHI-ACCESS-KEY, so it cannot be checked against the evidence');
} else if (!f66.includes('cors-probe.json')) {
  bad('F-66 does not link the evidence file');
} else {
  ok('F-66 published with the refused header named and the evidence linked');
}

/* --- 6. the retired in-browser-signing copy must not come back ------------ */
const RETIRED = [
  'signs requests in your browser from a key you paste',
  'signs requests locally in your browser from a key you paste',
  'can read your own account if you paste your own key',
];
for (const file of ['index.html', 'executive-summary.html', 'questions.html', 'flagged.html', 'README.md']) {
  if (!existsSync(file)) continue;
  const text = readFileSync(file, 'utf8');
  const hit = RETIRED.find((phrase) => text.replace(/\s+/g, ' ').includes(phrase));
  if (hit) {
    bad(`${file} still contains the retired claim: "${hit}" (a browser cannot send signed requests — F-66)`);
  } else {
    ok(`${file}: no retired in-browser-signing claim`);
  }
}

console.log(`\n${checks - failures}/${checks} checks passed.`);
if (failures) {
  console.error(`${failures} failure(s) — the published CORS claim and the measured evidence disagree.`);
  process.exit(1);
}
console.log('OK: the published CORS claim matches the recorded evidence.');
